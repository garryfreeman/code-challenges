import { test } from '../../tools';

function isValidSudoku(board: string[][]): boolean {
  const columnValues = new Set<string>();
  const sectionValues = new Set<string>();

  for (let c = 0; c < 9; c++) {
    const rowValues = new Set<string>();

    for (let r = 0; r < 9; r++) {
      const value = board[r][c];

      if (value === '.') continue;

      const columnCode = `${r}_${value}`;
      const sectionCode = `${Math.floor(r / 3)}_${Math.floor(c / 3)}_${value}`;

      if (rowValues.has(value) || columnValues.has(columnCode) || sectionValues.has(sectionCode)) {
        return false;
      }

      rowValues.add(value);
      columnValues.add(columnCode);
      sectionValues.add(sectionCode);
    }
  }

  return true;
}

